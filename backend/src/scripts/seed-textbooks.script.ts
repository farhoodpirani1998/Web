function normalizeSeed(seed: TextbookSeed): TextbookSeed {
  return {
    ...seed,
    title: { ...seed.title, fa: normalizePersianText(seed.title.fa) },
    stage: normalizePersianText(seed.stage),
    grade: normalizePersianText(seed.grade),
    field: seed.field === null ? null : normalizePersianText(seed.field),
    subject: normalizePersianText(seed.subject),
    academicYear: normalizePersianText(seed.academicYear),
    edition: seed.edition === null ? null : normalizePersianText(seed.edition),
    sourceAttribution: normalizePersianText(seed.sourceAttribution),
    licenseNote:
      seed.licenseNote === null ? null : normalizePersianText(seed.licenseNote),
  };
}

async function main(): Promise<void> {
  await AppDataSource.initialize();

  try {
    const insertedCount = await AppDataSource.transaction(async (manager) => {
      const siteRepository = manager.getRepository(Site);
      let site = await siteRepository.findOne({
        where: { key: DEFAULT_SITE_KEY },
      });
      if (!site) {
        site = await siteRepository.save(
          siteRepository.create({ key: DEFAULT_SITE_KEY, name: 'Main Site' }),
        );
      }

      const textbookRepository = manager.getRepository(Textbook);
      const existing = await textbookRepository.find({
        where: { siteId: site.id },
        select: ['code'],
      });
      const toInsert = getUnimportedTextbookSeeds(
        TEXTBOOK_SEEDS.map(normalizeSeed),
        new Set(existing.map((textbook) => textbook.code)),
      );

      if (toInsert.length === 0) return 0;

      const entities = textbookRepository.create(
        toInsert.map((seed) => ({ ...seed, siteId: site.id })),
      );
      await textbookRepository
        .createQueryBuilder()
        .insert()
        .into(Textbook)
        .values(entities)
        .orIgnore()
        .execute();

      return toInsert.length;
    });

    logger.log(
      insertedCount > 0
        ? `${insertedCount} عنوان کتاب نمونه با موفقیت اضافه شد.`
        : 'همه عنوان‌های کتاب نمونه از قبل ثبت شده‌اند.',
    );
  } finally {
    await AppDataSource.destroy();
  }
}

if (require.main === module) {
  main().catch((error: unknown) => {
    logger.error(
      'افزودن کتاب‌های نمونه با خطا روبه‌رو شد.',
      error instanceof Error ? error.stack : String(error),
    );
    process.exitCode = 1;
  });
}
